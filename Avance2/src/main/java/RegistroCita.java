    private void cargarCombos() {
        comboPaciente.removeAllItems();
        comboDoctor.removeAllItems();

        String sqlPacientes = "SELECT id, nombre FROM paciente ORDER BY id ASC";
        String sqlDoctores = "SELECT id, nombre FROM doctor ORDER BY id ASC";

        try (Connection conn = Conexion.conectar()) {
            // Cargar pacientes
            try (java.sql.PreparedStatement pstP = conn.prepareStatement(sqlPacientes);
                 java.sql.ResultSet rsP = pstP.executeQuery()) {
                while (rsP.next()) {
                    comboPaciente.addItem(rsP.getInt("id") + " - " + rsP.getString("nombre"));
                }
            }
            // Cargar doctores
            try (java.sql.PreparedStatement pstD = conn.prepareStatement(sqlDoctores);
                 java.sql.ResultSet rsD = pstD.executeQuery()) {
                while (rsD.next()) {
                    comboDoctor.addItem(rsD.getInt("id") + " - " + rsD.getString("nombre"));
                }
            }
        } catch (java.sql.SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al cargar pacientes/doctores: " + e.getMessage());
        }
    }
    
