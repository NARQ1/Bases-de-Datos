    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
       String sql = "INSERT INTO cita (id_paciente, id_doctor, fecha, hora) VALUES (?, ?, ?, ?)";

        try {
            if (comboPaciente.getSelectedItem() == null || comboDoctor.getSelectedItem() == null) {
                JOptionPane.showMessageDialog(this, "Selecciona un paciente y un doctor.");
                return;
            }

            String fechaTexto = obtenerFecha.getText().trim();
            String horaTexto = obtenerHora.getText().trim();

            if (fechaTexto.isEmpty() || horaTexto.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Completa los campos de fecha y hora.");
                return;
            }

            int idPaciente = Integer.parseInt(comboPaciente.getSelectedItem().toString().split(" - ")[0]);
            int idDoctor = Integer.parseInt(comboDoctor.getSelectedItem().toString().split(" - ")[0]);

            java.time.LocalDate fechaLocal = java.time.LocalDate.parse(
                fechaTexto,
                java.time.format.DateTimeFormatter.ofPattern("dd/MM/yyyy")
            );
            java.time.LocalTime horaLocal = java.time.LocalTime.parse(
                horaTexto,
                java.time.format.DateTimeFormatter.ofPattern("HH:mm")
            );

            int horaNum = horaLocal.getHour();
            if (horaNum == 14 || horaNum == 15) {
                JOptionPane.showMessageDialog(this, "No se pueden agendar citas entre 2:00 PM y 4:00 PM (Horario de comida).");
                return;
            }

            if (horaNum < 9 || horaNum > 19) {
                JOptionPane.showMessageDialog(this, "El horario de atención es de 09:00 a 19:00.");
                return;
            }

            String sqlVerificar = "SELECT COUNT(*) FROM cita WHERE id_doctor = ? AND fecha = ? AND hora = ?";
            try (Connection conn = Conexion.conectar();
                 java.sql.PreparedStatement pstCheck = conn.prepareStatement(sqlVerificar)) {

                pstCheck.setInt(1, idDoctor);
                pstCheck.setDate(2, java.sql.Date.valueOf(fechaLocal));
                pstCheck.setTime(3, java.sql.Time.valueOf(horaLocal));

                try (java.sql.ResultSet rs = pstCheck.executeQuery()) {
                    if (rs.next() && rs.getInt(1) > 0) {
                        JOptionPane.showMessageDialog(this, "El doctor ya tiene una cita ocupada en esa fecha y hora.");
                        return;
                    }
                }
            }

            try (Connection conn = Conexion.conectar();
                 java.sql.PreparedStatement pstmt = conn.prepareStatement(sql)) {

                pstmt.setInt(1, idPaciente);
                pstmt.setInt(2, idDoctor);
                pstmt.setDate(3, java.sql.Date.valueOf(fechaLocal));
                pstmt.setTime(4, java.sql.Time.valueOf(horaLocal));

                pstmt.executeUpdate();
                JOptionPane.showMessageDialog(this, "¡Cita registrada correctamente!");

                obtenerFecha.setText("");
                obtenerHora.setText("");
            }
        } catch (java.time.format.DateTimeParseException ex) {
            JOptionPane.showMessageDialog(this, "Formato inválido.\nFecha: dd/MM/yyyy (ej. 23/11/2026)\nHora: HH:mm (ej. 09:00)");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al registrar la cita: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton1ActionPerformed

