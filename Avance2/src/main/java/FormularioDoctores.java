    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
            // TODO add your handling code here:
            String sql = "INSERT INTO doctor VALUES(?,?,?,?,?,?,?,?)";

            try {
                int id = Integer.parseInt(obtenerID.getText().trim());
                String nombre = obtenerNombre.getText().trim();
                String direccion = obtenerDireccion.getText().trim();
                long telefono = Long.parseLong(obtenerTelefono.getText().trim());
                String fecha_nac = obtenerFecha_nac.getText().trim();
                String sexo = obtenerSexo.getText().trim();
                String especialidad = obtenerEspecialidad.getText().trim();
                String contrasena = String.valueOf(obtenerContrasena.getPassword());

                if (sexo.isEmpty()) {
                    JOptionPane.showMessageDialog(null, "El campo Sexo no puede estar vacío.");
                    return;
                }
                String sexoChar = String.valueOf(sexo.charAt(0));

                java.time.LocalDate fechaLocal = java.time.LocalDate.parse(
                        fecha_nac,
                        java.time.format.DateTimeFormatter.ofPattern("dd/MM/yyyy")
                );

                try (Connection conn = Conexion.conectar(); java.sql.PreparedStatement pstmt = conn.prepareStatement(sql)) {

                    pstmt.setInt(1, id);
                    pstmt.setString(2, nombre);
                    pstmt.setString(3, direccion);
                    pstmt.setLong(4, telefono);
                    pstmt.setDate(5, java.sql.Date.valueOf(fechaLocal));
                    pstmt.setString(6, sexoChar);
                    pstmt.setString(7, especialidad);
                    pstmt.setString(8, contrasena);

                    pstmt.executeUpdate();
                    String nombreCorto = nombre.trim();
                    int posicionEspacio = nombreCorto.indexOf(" ");

                    if (posicionEspacio != -1) {
                        nombreCorto = nombreCorto.substring(0, posicionEspacio);
                    }

                    JOptionPane.showMessageDialog(null, "Se ha ingresado correctamente al doctor " + nombreCorto + "!");

                }
            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, "Error al insertar los datos: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton2ActionPerformed

